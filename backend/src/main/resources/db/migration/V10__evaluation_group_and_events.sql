CREATE TABLE IF NOT EXISTS evaluation_player (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL UNIQUE,
    evaluation_id BIGINT NOT NULL,
    player_id BIGINT NOT NULL,
    assigned_date DATE NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_evaluation_player_evaluation FOREIGN KEY (evaluation_id) REFERENCES evaluation(id),
    CONSTRAINT fk_evaluation_player_player FOREIGN KEY (player_id) REFERENCES player(id)
);

CREATE INDEX IF NOT EXISTS idx_evaluation_player_evaluation_active ON evaluation_player(evaluation_id, active);
CREATE INDEX IF NOT EXISTS idx_evaluation_player_player_active ON evaluation_player(player_id, active);

CREATE TABLE IF NOT EXISTS evaluation_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL UNIQUE,
    evaluation_id BIGINT NOT NULL,
    place VARCHAR(150) NOT NULL,
    event_date DATE NOT NULL,
    start_time TIME NOT NULL,
    duration_minutes INT NOT NULL CHECK (duration_minutes IN (60, 90, 120)),
    status VARCHAR(20) NOT NULL CHECK (status IN ('SCHEDULED', 'COMPLETED', 'CANCELED')),
    cancel_reason VARCHAR(255),
    CONSTRAINT fk_evaluation_event_evaluation FOREIGN KEY (evaluation_id) REFERENCES evaluation(id)
);

CREATE INDEX IF NOT EXISTS idx_evaluation_event_evaluation ON evaluation_event(evaluation_id);

CREATE TABLE IF NOT EXISTS evaluation_event_attendance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL UNIQUE,
    evaluation_event_id BIGINT NOT NULL,
    player_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('PRESENT', 'ABSENT')),
    skill_level VARCHAR(20) NOT NULL CHECK (skill_level IN ('DEBUTANT', 'ADVANCED', 'SKILLED')),
    reason VARCHAR(255),
    CONSTRAINT fk_evaluation_event_attendance_event FOREIGN KEY (evaluation_event_id) REFERENCES evaluation_event(id),
    CONSTRAINT fk_evaluation_event_attendance_player FOREIGN KEY (player_id) REFERENCES player(id)
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_evaluation_event_attendance_player
    ON evaluation_event_attendance(evaluation_event_id, player_id);

CREATE TABLE IF NOT EXISTS evaluation_result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL UNIQUE,
    evaluation_id BIGINT NOT NULL,
    player_id BIGINT NOT NULL,
    source_event_id BIGINT NOT NULL,
    level_result VARCHAR(20) NOT NULL CHECK (level_result IN ('DEBUTANT', 'ADVANCED', 'SKILLED')),
    attendance_status VARCHAR(20) NOT NULL CHECK (attendance_status IN ('PRESENT', 'ABSENT')),
    finalized_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_evaluation_result_evaluation FOREIGN KEY (evaluation_id) REFERENCES evaluation(id),
    CONSTRAINT fk_evaluation_result_player FOREIGN KEY (player_id) REFERENCES player(id),
    CONSTRAINT fk_evaluation_result_source_event FOREIGN KEY (source_event_id) REFERENCES evaluation_event(id),
    CONSTRAINT uk_evaluation_result_player UNIQUE (evaluation_id, player_id)
);

CREATE INDEX IF NOT EXISTS idx_evaluation_result_evaluation
    ON evaluation_result(evaluation_id);

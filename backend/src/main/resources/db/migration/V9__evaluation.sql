CREATE TABLE evaluation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID NOT NULL UNIQUE,
    title VARCHAR(150) NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('OPEN', 'IN_PROGRESS', 'FINALIZED')),
    team_id BIGINT NOT NULL,
    created_date DATE NOT NULL,
    CONSTRAINT fk_evaluation_team FOREIGN KEY (team_id) REFERENCES team(id)
);

CREATE INDEX idx_evaluation_team ON evaluation(team_id);
CREATE INDEX idx_evaluation_status ON evaluation(status);

